    id("dev.flutter.flutter-gradle-plugin")
}

// Release signing: keys/key.properties at the repository root (gitignored). CI recreates it from secrets.
val keyPropertiesFile = rootProject.file("../keys/key.properties")
val keyProperties = Properties().apply {
    if (keyPropertiesFile.exists()) keyPropertiesFile.inputStream().use { load(it) }
}
val hasReleaseKey = keyPropertiesFile.exists()
if (!hasReleaseKey && System.getenv("REQUIRE_RELEASE_SIGNING") == "true") {
    throw GradleException("Release signing required but ${keyPropertiesFile.path} is missing")
}

android {
    namespace = "com.gatekeeper.app"
    compileSdk = 36
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    defaultConfig {
        applicationId = "com.gatekeeper.app"
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        minSdk = 30
        targetSdk = 36
        // Uses the version code from pubspec.yaml. When using split APKs, 1000 * ABI_VERSION
        // is added automatically by Flutter. (https://developer.android.com/studio/build/configure-apk-splits#configure-APK-versions)
        // You can force using the value of versionCode by specifying the `-P force-version-code-ignoring-abi=true`
        // flag during build.
        versionCode = flutter.versionCode
        versionName = flutter.versionName
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    lint {
        // local.properties is generated by the Flutter tool with unescaped Windows paths.
        disable += "PropertyEscape"
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }

    signingConfigs {
        if (hasReleaseKey) {
            create("release") {
                storeFile = keyPropertiesFile.parentFile.resolve(keyProperties.getProperty("storeFile"))
                storePassword = keyProperties.getProperty("storePassword")
                keyAlias = keyProperties.getProperty("keyAlias")
                keyPassword = keyProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // Without keys/key.properties (e.g. a fresh clone) release builds fall back to the debug key.
            // Such APKs cannot update an installed release build.
            signingConfig = if (hasReleaseKey) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
        }
    }
}

